// Synthetic accounts and isolated 8766 fixture only. Run with playwright-cli run-code.
async page => {
  const base='http://127.0.0.1:8766', results=[], errors=[];
  if(!page.url().startsWith(base+'/'))throw new Error('Only the isolated 8766 preview is allowed');
  const check=(value,name)=>{if(!value)throw new Error(name);results.push(name);};
  page.on('pageerror',error=>errors.push(error.message));
  await page.context().clearCookies();
  await page.goto(base+'/login?next=%2Faccounts');
  await page.getByLabel('登录账号',{exact:true}).fill('preview-admin');
  await page.getByLabel('密码',{exact:true}).fill('Preview-Admin-2026');
  await page.getByRole('button',{name:'登录工作台',exact:true}).click();
  await page.waitForURL(base+'/accounts');
  await page.locator('#account-count').filter({hasText:'个账号'}).waitFor();
  await page.route('**/api/v1/auth/me',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'模拟身份服务暂不可用'})}));
  await page.reload();
  await page.getByRole('button',{name:'重试连接',exact:true}).waitFor();
  check(await page.getByRole('button',{name:'重试连接',exact:true}).isEnabled(),'Identity loading failure offers an enabled retry');
  await page.unroute('**/api/v1/auth/me');
  await page.getByRole('button',{name:'重试连接',exact:true}).click();
  await page.locator('#account-count').filter({hasText:'个账号'}).waitFor();
  check(await page.getByRole('button',{name:'刷新列表',exact:true}).isEnabled(),'Retry identity restores normal access');
  check(await page.locator('#editor-empty').isVisible(),'Explicit initial empty state');
  await page.getByLabel('角色',{exact:true}).selectOption('field_engineer');
  check(!(await page.locator('#account-list').textContent()).includes('preview-admin'),'Role filter');
  await page.getByLabel('状态',{exact:true}).selectOption('pending');
  check((await page.locator('#account-list').textContent()).includes('待设置密码'),'Pending filter');
  await page.getByLabel('搜索账号或姓名',{exact:true}).fill('no-such-account-xyz');
  check(await page.locator('.directory-empty').isVisible(),'Search empty state');
  await page.getByRole('button',{name:'清除筛选',exact:true}).click();
  await page.getByRole('button',{name:'设置 普通用户（tunnel-reader）',exact:true}).click();
  await page.getByLabel('显示名称',{exact:true}).fill('未保存测试');
  await page.getByRole('button',{name:'设置 系统管理员（preview-admin）',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  check(await page.getByRole('button',{name:'继续编辑',exact:true}).evaluate(el=>document.activeElement===el),'Discard dialog safe default focus');
  await page.keyboard.press('Escape');
  check(await page.getByLabel('显示名称',{exact:true}).inputValue()==='未保存测试','Escape preserves edits');
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await page.getByRole('button',{name:'继续编辑',exact:true}).click();
  check(await page.getByLabel('显示名称',{exact:true}).inputValue()==='未保存测试','Cancel can keep changes');
  await page.getByRole('button',{name:'设置 系统管理员（preview-admin）',exact:true}).click();
  await page.getByRole('button',{name:'放弃修改',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#account-username').value==='preview-admin');
  check(await page.getByLabel('账号角色',{exact:true}).isDisabled(),'Current administrator cannot change own role');
  check(await page.getByLabel('账号状态',{exact:true}).isDisabled(),'Current administrator cannot disable self');
  const username='ui-reader-'+Date.now().toString(36);
  await page.getByRole('button',{name:'＋ 新增账号',exact:true}).click();
  await page.getByLabel('登录账号',{exact:true}).fill(username);
  await page.getByLabel('显示名称',{exact:true}).fill('界面验证成员');
  await page.getByLabel('设置新密码',{exact:true}).fill('Preview-Reader-2026');
  await page.getByLabel('再次输入新密码',{exact:true}).fill('not-the-same');
  check(await page.locator('#confirm-password').evaluate(el=>!el.validity.valid),'Password mismatch native validation');
  await page.getByLabel('再次输入新密码',{exact:true}).fill('Preview-Reader-2026');
  await page.getByLabel('管理员当前密码',{exact:true}).fill('Preview-Admin-2026');
  let release, postCount=0;
  const gate=new Promise(resolve=>release=resolve);
  await page.route('**/api/v1/accounts',async route=>{
    if(route.request().method()==='POST'){postCount++;await gate;await route.continue();}
    else await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'模拟列表暂不可用'})});
  });
  await page.getByRole('button',{name:'保存账号设置',exact:true}).click();
  check(await page.getByLabel('显示名称',{exact:true}).isDisabled(),'Saving locks fields');
  check(await page.getByRole('button',{name:'＋ 新增账号',exact:true}).isDisabled(),'Saving locks create action');
  check(await page.getByRole('button',{name:'取消',exact:true}).isDisabled(),'Saving locks cancel action');
  check(await page.locator('.account-row').first().isDisabled(),'Saving locks directory selection');
  await page.locator('#account-form').evaluate(form=>{form.requestSubmit();form.requestSubmit();});
  release();
  await page.locator('#page-feedback').filter({hasText:'账号已保存，但列表同步暂不可用'}).waitFor();
  check(postCount===1,'Saving prevents duplicate submissions');
  check((await page.locator('#form-feedback').textContent()).includes('账号已保存'),'Refresh failure does not misreport save');
  check(await page.getByLabel('登录账号',{exact:true}).inputValue()===username,'Committed account remains selected');
  check(await page.getByLabel('设置新密码',{exact:true}).inputValue()==='','Saved password cleared');
  await page.unroute('**/api/v1/accounts');
  await page.getByRole('button',{name:'刷新列表',exact:true}).click();
  await page.locator('#page-feedback').filter({hasText:'账号列表已刷新'}).waitFor();
  check(postCount===1,'Refresh does not re-create account');
  await page.getByLabel('显示名称',{exact:true}).fill('刷新不会覆盖草稿');
  await page.getByLabel('管理员当前密码',{exact:true}).fill('Preview-Admin-2026');
  let releaseRefresh, prematureWrites=0;
  const refreshGate=new Promise(resolve=>releaseRefresh=resolve);
  const countPremature=request=>{if(request.method()==='PUT')prematureWrites++;};
  page.on('request',countPremature);
  await page.route('**/api/v1/accounts',async route=>{await refreshGate;await route.continue();});
  await page.getByRole('button',{name:'刷新列表',exact:true}).click();
  check(await page.getByRole('button',{name:'保存账号设置',exact:true}).isDisabled(),'Refresh in flight prevents saving stale metadata');
  check(await page.getByLabel('显示名称',{exact:true}).isEnabled(),'Refresh still permits editing draft text');
  await page.locator('#account-form').evaluate(form=>form.requestSubmit());
  releaseRefresh();
  await page.waitForFunction(()=>!document.querySelector('#refresh-accounts').disabled);
  await page.unroute('**/api/v1/accounts');
  page.off('request',countPremature);
  check(prematureWrites===0,'Submit guard blocks writes during refresh');
  check(await page.getByRole('button',{name:'保存账号设置',exact:true}).isEnabled(),'Save resumes after refresh completes');
  await page.locator('#page-feedback').filter({hasText:'账号列表已刷新'}).waitFor();
  check(await page.getByLabel('显示名称',{exact:true}).inputValue()==='刷新不会覆盖草稿','List refresh preserves unsaved fields');
  await page.getByLabel('管理员当前密码',{exact:true}).fill('Preview-Admin-2026');
  let putCount=0;
  await page.route('**/api/v1/accounts/*',async route=>{putCount++;await route.continue();});
  await page.getByRole('button',{name:'保存账号设置',exact:true}).click();
  await page.locator('#form-feedback').filter({hasText:'账号已保存'}).waitFor();
  check(putCount===1,'Existing returned account ID used for subsequent PUT');
  await page.unroute('**/api/v1/accounts/*');
  const widths=[];
  for(const width of [360,768,1024,1440]){
    await page.setViewportSize({width,height:1000});
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Account layout fits '+width);
    widths.push(width);
  }
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'output/playwright/accounts-verified-desktop.png',fullPage:true});
  await page.setViewportSize({width:360,height:900});
  await page.getByRole('button',{name:'设置 普通用户（tunnel-reader）',exact:true}).click();
  check(await page.locator('#editor-title').evaluate(el=>el.getBoundingClientRect().top<innerHeight),'Mobile selection reveals editor');
  await page.screenshot({path:'output/playwright/accounts-verified-mobile.png'});
  await page.getByLabel('显示名称',{exact:true}).fill('不会自动重放的修改');
  await page.getByLabel('管理员当前密码',{exact:true}).fill('Preview-Admin-2026');
  const other=await page.context().newPage();
  await other.goto(base+'/accounts');
  await other.getByRole('button',{name:'退出登录',exact:true}).click();
  await other.waitForURL('**/login?reason=logged_out');
  await other.getByLabel('登录账号',{exact:true}).fill('preview-admin');
  await other.getByLabel('密码',{exact:true}).fill('Preview-Admin-2026');
  await other.getByRole('button',{name:'登录工作台',exact:true}).click();
  await other.waitForURL(base+'/');
  await other.close();
  let requests=0;
  await page.route('**/api/v1/accounts/*',async route=>{requests++;await route.continue();});
  await page.getByRole('button',{name:'保存账号设置',exact:true}).click();
  await page.getByRole('button',{name:'重新验证身份',exact:true}).waitFor();
  check(await page.getByLabel('显示名称',{exact:true}).isDisabled(),'Changed session locks editor');
  check(await page.getByLabel('管理员当前密码',{exact:true}).inputValue()==='','Changed session clears secrets');
  check(requests===1,'Changed session never automatically replays mutation');
  await page.getByRole('button',{name:'重新验证身份',exact:true}).click();
  await page.getByRole('button',{name:'放弃修改',exact:true}).click();
  await page.locator('#editor-empty').waitFor();
  check(requests===1,'Revalidation does not replay pending mutation');
  await page.unroute('**/api/v1/accounts/*');
  check(errors.length===0,'No unhandled browser errors');
  await page.getByRole('button',{name:'退出登录',exact:true}).click();
  await page.waitForURL('**/login?reason=logged_out');
  return {status:'passed',assertions:results.length,widths,checks:results};
}
